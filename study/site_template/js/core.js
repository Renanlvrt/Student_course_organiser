  S.copy = async function (text) {
    try { await navigator.clipboard.writeText(text); S.toast("Copied. Paste it into Claude or Gemini."); }
    catch (e) { const t = S.h("textarea", {}, text); document.body.append(t); t.select(); document.execCommand("copy"); t.remove(); S.toast("Copied."); }
  };

  S.exercise = function (ex, opts) {
    opts = opts || {};
    const box = S.h("article", { class: "ex", id: ex.id });
    const meta = S.h("div", { class: "meta" },
      S.h("span", { class: "layer" }, { practical: "Practical", drill: "Drill", exam: "Exam style", transfer: "New angle", interleaved: "Mixed" }[ex.layer] || ex.layer || ""),
      ex.difficulty ? S.h("span", {}, "Difficulty " + ex.difficulty + "/5") : null,
      ex.marks ? S.h("span", {}, ex.marks + " marks") : null,
      ex.src ? S.h("span", {}, String(ex.src)) : null);
    box.append(meta, S.mdEl("div", ex.question), ex.given ? S.mdEl("div", ex.given) : "");
    const c = ex.check || { type: "none" };
    let input;
    const verdict = S.h("div", { class: "verdict", "aria-live": "polite" });
    const reveal = S.h("div", { class: "reveal", hidden: true });
    function finish(ok, value) {
      box.classList.remove("right", "wrong");
      if (ok === true || ok === false) {
        box.classList.add(ok ? "right" : "wrong");
        verdict.className = "verdict " + (ok ? "right" : "wrong");
        verdict.textContent = ok ? "Correct." : "Not quite. Check the hints, then the solution.";
        S.progress.record(ex.id, ex.concepts, ok);
      }
      reveal.hidden = false;
      if (opts.onAnswer) opts.onAnswer(ok, value);
    }
    if (c.type === "mcq" && Array.isArray(ex.options)) {
      const name = "q-" + ex.id;
      input = S.h("div", { class: "opts", role: "radiogroup" }, ex.options.map((o, k) =>
        S.h("label", {}, S.h("input", { type: "radio", name, value: String(k) }), S.mdEl("span", o))));
      box.append(input, S.h("div", { class: "answer" }, S.h("button", { class: "primary", onclick: () => {
        const sel = input.querySelector("input:checked"); if (!sel) return S.toast("Pick an option first.");
        const v = sel.value, txt = ex.options[+v];
        finish(String(c.answer) === v || normalise(c.answer) === normalise(txt), txt);
      } }, "Check")));
    } else if (c.type && c.type !== "none") {
      input = S.h("input", { type: "text", "aria-label": "Your answer", placeholder: c.type === "numeric" ? "a number" : "your answer",
        onkeydown: (e) => { if (e.key === "Enter") btn.click(); } });
      const btn = S.h("button", { class: "primary", onclick: () => finish(check(ex, input.value), input.value) }, "Check");
      box.append(S.h("div", { class: "answer" }, input, btn));
    } else {
      input = S.h("textarea", { "aria-label": "Your answer", placeholder: "Write your answer as you would in the exam…" });
      box.append(input, S.h("div", { class: "answer" },
        S.h("button", { class: "primary", onclick: () => finish(null, input.value) }, "I've answered: show the solution"),
        S.h("button", { onclick: () => S.copy(S.askClaudePrompt(ex, input.value)) }, "Ask Claude to mark it"),
        S.h("button", { onclick: () => finish(true, input.value), title: "Record as correct after comparing with the solution" }, "I got it"),
        S.h("button", { onclick: () => finish(false, input.value), title: "Record as wrong so it comes back" }, "I missed it")));
    }
    box.append(verdict);
    (ex.hints || []).forEach((hint, k) => box.append(S.h("details", {}, S.h("summary", {}, "Hint " + (k + 1)), S.mdEl("div", hint))));
    if (ex.strategy) reveal.append(S.h("h4", {}, "How to attack this type of question"), S.mdEl("div", ex.strategy));
    if (ex.solution) reveal.append(S.h("h4", {}, "Solution"), S.mdEl("div", ex.solution));
    if (ex.mark_scheme && ex.mark_scheme.length) reveal.append(S.h("h4", {}, "Mark scheme"), S.mdEl("div", ex.mark_scheme.map((m) => "- " + m).join("\n")));
    if (ex.common_mistakes && ex.common_mistakes.length) reveal.append(S.h("h4", {}, "Common mistakes"), S.mdEl("div", ex.common_mistakes.map((m) => "- " + m).join("\n")));
    box.append(S.h("details", { ontoggle: (e) => { if (e.target.open) reveal.hidden = false; } }, S.h("summary", {}, "Show the solution now")), reveal);
    return box;
  };

  /* ---------------------------------------------------------------- flashcards session */
  S.cardSession = function (cards, mount) {
    let queue = S.srs.due(cards);
    function next() {
      mount.replaceChildren();
      if (!queue.length) {
        mount.append(S.h("p", { class: "muted" }, cards.length ? "No cards due. Come back later, or study them all again."
          : "No flashcards for this yet."), cards.length ? S.h("button", { onclick: () => { queue = cards.slice(); next(); } }, "Study all " + cards.length + " cards") : "");
        return;
      }
      const c = queue[0];
      const back = S.mdEl("div", c.back, "back"); back.hidden = true;
      const grade = S.h("div", { class: "grade", hidden: true },
        [["Again", 0], ["Hard", 1], ["Good", 2], ["Easy", 3]].map(([l, q]) => S.h("button", { class: q === 2 ? "primary" : "", onclick: () => {
          S.srs.grade(c.id, q); queue.shift(); if (q === 0) queue.push(c); next(); } }, l)));
      const show = S.h("button", { class: "primary", onclick: () => { back.hidden = false; grade.hidden = false; show.remove(); } }, "Show answer");
      mount.append(S.h("p", { class: "muted ui" }, queue.length + " to go"),
        S.h("div", { class: "card" }, S.h("span", { class: "layer" }, { recall: "Recall", understanding: "Understanding", boundaries: "Edge cases" }[c.layer] || ""),
          S.mdEl("div", c.front), back), show, grade);
    }
    next();
  };

